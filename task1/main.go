package main

import (
	"fmt"
	"strings" // пакет strings нужен для функции Join
)

// ------------------------------------------------------------
// changeSlice - функция, которая изменяет первый элемент слайса
// ------------------------------------------------------------
// Параметр arr - слайс строк ([]string).
// Слайс в Go — это "хедер", который содержит:
//   - указатель на массив (backing array)
//   - текущую длину len
//   - ёмкость cap
//
// Важно: при передаче слайса в функцию копируется только хедер,
// но массив остаётся общим. Поэтому изменение arr[0]
// изменяет данные, видимые снаружи функции.
func changeSlice(arr []string) {
	arr[0] = "Goodbye"
}

// ------------------------------------------------------------
// appendSomeData - функция, которая пытается добавить элемент в слайс
// ------------------------------------------------------------
// Важно:
// append может создать новый массив (реаллокацию), если текущий массив заполнен.
// Но хедер слайса передан в функцию по значению.
// Изменение хедера внутри функции НЕ влияет на внешний слайс.
//
// Чтобы изменения были видны снаружи, нужно возвращать новый слайс:
//
//	arr = append(arr, "!")
//	return arr
func appendSomeData(arr []string) {
	arr = append(arr, "!") // локальное изменение, внешний слайс не меняется
}

// ------------------------------------------------------------
// main - точка входа программы
// ------------------------------------------------------------
func main() {
	// Создаём слайс с литералом
	// []string{"Hello", "World"}:
	//   • создаётся массив ["Hello", "World"]
	//   • создаётся хедер слайса:
	//       data -> указатель на массив
	//       len = 2
	//       cap = 2
	someSlice := []string{"Hello", "World"}

	// Вызов changeSlice
	// Копия хедера передаётся в функцию, но она указывает на тот же массив.
	// Поэтому первый элемент меняется, и изменение видно снаружи.
	changeSlice(someSlice)

	// Вызов appendSomeData
	// Внутри функции создаётся новый хедер (возможно новый массив),
	// но внешний someSlice НЕ меняется.
	appendSomeData(someSlice)

	// strings.Join соединяет элементы слайса в одну строку
	// Второй аргумент - разделитель между элементами, в данном случае пустая строка ""
	// Вывод в консоль: "GoodbyeWorld"
	fmt.Println(strings.Join(someSlice, ""))
}

// ------------------------------------------------------------
// Тип slice - демонстрационный, показывает внутреннюю структуру слайса
// В реальном Go это не нужно для работы с слайсами
// ------------------------------------------------------------
type slice struct {
	zero *any // указатель на массив
	len  int  // длина слайса
	cap  int  // вместимость слайса
}

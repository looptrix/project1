package main
import "fmt"

// Обьявим тип car - структура с полями, описывающими машину.
// Car - имя типа заглавной буквы, значит тип "экспортируемый",
//но это больше актуально для использования в других пакетах).
// struct -объвляем структуру(набор полей)
type Car struct {
	Brand string // марка автомобиля
	Model string // модель
	Year int // год выпуска
	Mileage int // пробег
}

type ServiceOrder struct{
	//ServiceOrder - заказ на обслуживание или ремонт автомобиля.
	ID 	int    // ID - номер заказа (целое число)
	Car Car    // Car - сама машина, по которой создан заказ (вложенная структура car)
	Description string // описание проблемы, что нужно сделать
	Cost float64 // Cost - стоимость ремонта/услуги в деьгах, тип float64
}
// Метод который увеличивает пробег машины
func (c *Car) AssMileage(km int)
// func - объявление функции /метода
// (с *Car) - это "приемник" метода (receiver).
//  	c- локальное имя переменной, которое указывает на car.
//	 	*Car - тип приёмника:"указатель на Car"
//		Это значит, что внутри метода мы работаем с исходной
//		машиной и можем изменять ее поля.
// (km int) - параметр метода 
if km < 0 {
	// if - условный оператор
	// km < 0 - условие: если километры отрицательные, это странно
	// пробег не может уменьшаться.
	fmt.Println("нельзя добавить отрицательный пробег")
	return 
	// return - выход из функции/метода
}
c.Mileage = c.Mileage + km
// c.Mileage - обращаемся к полю Mileage у приемника с (указатель на Car).
// c.Mileage + km - берем старый пробеги добавляем километры km.
// = - оператор присваивания

// Метод который помечает заказ как завершенный и задает стоимость.
func (o *ServiceOrder) Complete(cost float64) {
	// (o *ServiceOrder) — приёмник метода, o — указатель на ServiceOrder.
    // Complete — имя метода.
    // (cost float64) — параметр: цена, тип float64.

    if cost < 0 {
        fmt.Println("Стоимость не может быть отрицательной")
        return
    }

    o.IsCompleted = true // ставим флаг завершения
    o.Cost = cost        // записываем стоимость
}

// Метод, который печатает информацию о заказе.
func (o ServiceOrder) PrintInfo() {
    // Здесь приёмник не указатель, а "значение":
    // (o ServiceOrder) — копия структуры.
    // Мы ничего не меняем внутри заказа, только читаем его и печатаем,
    // поэтому указатель не обязателен.

    fmt.Println("----- Заказ -----")
    fmt.Println("ID:", o.ID)
    fmt.Println("Описание:", o.Description)
    fmt.Println("Завершён:", o.IsCompleted)
    fmt.Println("Стоимость:", o.Cost)

    fmt.Println("----- Машина -----")
    fmt.Println("Марка:", o.Car.Brand)
    fmt.Println("Модель:", o.Car.Model)
    fmt.Println("Год:", o.Car.Year)
    fmt.Println("Пробег:", o.Car.Mileage)
}
func main() {
    // func main() — специальная функция, с неё начинается выполнение
    // программы в пакете main.

    // 1. Создадим машину
    car := Car{
        // car — имя переменной.
        // :=  — короткое объявление переменной и сразу присваивание.
        // Car{ ... } — литерал структуры Car.
        Brand:   "Toyota",
        Model:   "Camry",
        Year:    2015,
        Mileage: 150000,
    }

    // 2. Создадим заказ на обслуживание
    order := ServiceOrder{
        ID:          1,
        Car:         car, // используем только что созданную машину
        Description: "Замена масла и диагностика подвески",
        IsCompleted: false, // заказ пока не выполнен
        Cost:        0,     // стоимость пока не известна
    }

    // 3. Печатаем исходное состояние заказа
    fmt.Println("СОСТОЯНИЕ ДО ОБСЛУЖИВАНИЯ:")
    order.PrintInfo() // вызываем метод PrintInfo у переменной order

    // 4. Машина приехала и проехала 20 км до сервиса
    car.AddMileage(20)
    // ВАЖНО: сейчас мы изменили пробег у переменной car,
    // но в order.Car лежит копия машины с предыдущим пробегом.
    // Это хороший повод обсудить значения и указатели позже :)

    // Обновим машину внутри заказа, чтобы там был актуальный пробег
    order.Car = car

    // 5. Завершаем заказ с ценой, например 120.50
    order.Complete(120.50)

    // 6. Печатаем конечное состояние заказа
    fmt.Println()
    fmt.Println("СОСТОЯНИЕ ПОСЛЕ ОБСЛУЖИВАНИЯ:")
    order.PrintInfo()
}
